"""ORM models — world country energy profiles (Cursor Wave 10).

Source: Our World in Data energy dataset
(https://github.com/owid/energy-data), real dataset with 130 columns as of
this wave's audit (the brief's "134" is stale — OWID revises the dataset on
its own cadence; reported as measured, not corrected to match the brief).

FIELD_DEFINITIONS is the single source of truth for the 12 ingested metric
columns. Every entry is copied verbatim from the real codebook
(``owid-energy-codebook.csv``, fetched from
``https://raw.githubusercontent.com/owid/energy-data/master/owid-energy-codebook.csv``
— the URL in the brief, ``owid-public.owid.io/.../owid-energy-codebook.csv``,
404s; the JSON data URL in the brief is correct and unrelated). No citation
or unit here was invented — both the ingest script and
``country_energy_field_source`` read from this same list, so the schema and
the API can never drift from what the codebook actually says.

Field selection (Fase 1), mapped to the brief's requested shape:
  - matriz por combustível: fossil_share_elec, nuclear_share_elec,
    hydro_share_elec, wind_share_elec, solar_share_elec, biofuel_share_elec,
    other_renewables_share_elec_exc_biofuel (excludes bioenergy so it does
    not double-count against biofuel_share_elec)
  - geração total: electricity_generation
  - participação de renovável: renewables_share_elec
  - intensidade de carbono: carbon_intensity_elec
  - consumo per capita: energy_per_capita (primary energy, not just
    electricity — deliberately broader than the generation figure)
  - population: kept as context, not part of the brief's explicit list, but
    required to make any "per capita" figure interpretable without a second
    lookup.

Deliberately NOT ingested: per-fuel sub-splits of "fossil" (coal/gas/oil
electricity shares), and the *_share_energy (primary-energy-basis) variants
of the same fuels — the brief asks for the aggregated matrix, not the full
134(130)-column surface, and the *_share_elec variants (Ember-sourced) have
materially better country coverage in the most recent year than the
*_share_energy (Energy Institute-sourced) ones, which cover roughly the
~90 countries Energy Institute reports on rather than the full sovereign set.
"""

