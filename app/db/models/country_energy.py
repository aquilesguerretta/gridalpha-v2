class CountryEnergyProfile(Base):
    __tablename__ = "country_energy_profile"
    __table_args__ = (UniqueConstraint("iso_code", name="country_energy_profile_iso_code_key"),)

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    iso_code: Mapped[str] = mapped_column(Text, nullable=False)
    country_name: Mapped[str] = mapped_column(Text, nullable=False)
    year: Mapped[int] = mapped_column(Integer, nullable=False)

    population: Mapped[int | None] = mapped_column(BigInteger, nullable=True)
    electricity_generation: Mapped[float | None] = mapped_column(Numeric(14, 4), nullable=True)
    renewables_share_elec: Mapped[float | None] = mapped_column(Numeric(6, 3), nullable=True)
    carbon_intensity_elec: Mapped[float | None] = mapped_column(Numeric(9, 3), nullable=True)
    energy_per_capita: Mapped[float | None] = mapped_column(Numeric(12, 3), nullable=True)
    fossil_share_elec: Mapped[float | None] = mapped_column(Numeric(6, 3), nullable=True)
    nuclear_share_elec: Mapped[float | None] = mapped_column(Numeric(6, 3), nullable=True)
    hydro_share_elec: Mapped[float | None] = mapped_column(Numeric(6, 3), nullable=True)
    wind_share_elec: Mapped[float | None] = mapped_column(Numeric(6, 3), nullable=True)
    solar_share_elec: Mapped[float | None] = mapped_column(Numeric(6, 3), nullable=True)
    biofuel_share_elec: Mapped[float | None] = mapped_column(Numeric(6, 3), nullable=True)
    other_renewables_share_elec_exc_biofuel: Mapped[float | None] = mapped_column(
        Numeric(6, 3), nullable=True
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )


class CountryEnergyFieldSource(Base):
    """One row per ingested metric column — citation + unit for the API to serve.

    Population and the eleven mix/generation/intensity/per-capita metrics
    all get a row; ``iso_code``/``country_name``/``year`` are keys, not
    metrics, so they are not represented here.
    """

    __tablename__ = "country_energy_field_source"

    field_name: Mapped[str] = mapped_column(Text, primary_key=True)
    source_citation: Mapped[str] = mapped_column(Text, nullable=False)
    unit: Mapped[str] = mapped_column(Text, nullable=False)
